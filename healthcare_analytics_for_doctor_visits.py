"""### Univariate Analysis

Let's start by visualizing the distribution of some key numerical features like `age`, `income`, and `visits` using histograms. Then, we will look at the distribution of categorical features, starting with `gender`.
"""

# Plotting histograms for numerical features
fig, axes = plt.subplots(1, 3, figsize=(18, 6))

sns.histplot(df['age'], kde=True, ax=axes[0], color='skyblue')
axes[0].set_title('Distribution of Age')
axes[0].set_xlabel('Age')
axes[0].set_ylabel('Frequency')

sns.histplot(df['income'], kde=True, ax=axes[1], color='lightcoral')
axes[1].set_title('Distribution of Income')
axes[1].set_xlabel('Income')
axes[1].set_ylabel('Frequency')

sns.histplot(df['visits'], kde=True, ax=axes[2], color='lightgreen')
axes[2].set_title('Distribution of Visits')
axes[2].set_xlabel('Number of Visits')
axes[2].set_ylabel('Frequency')

plt.tight_layout()
plt.show()

# Plotting a bar plot for the 'gender' categorical feature
plt.figure(figsize=(8, 6))
sns.countplot(x='gender', data=df, palette='viridis', hue='gender', legend=False)
plt.title('Distribution of Gender')
plt.xlabel('Gender')
plt.ylabel('Count')
plt.show()



"""### Gender Analysis: Counts

Let's get the precise counts for each gender category in the dataset.
"""

# Get the count of each gender
gender_counts = df['gender'].value_counts()
display(gender_counts)

gender_analysis = (
    df.groupby("gender")["visits"]
      .agg(["count", "mean", "median"])
      .reset_index()
)

display(gender_analysis)

sns.barplot(
    data=gender_analysis,
    x="gender",
    y="mean",
    color="teal"
)

plt.title("Average Doctor Visits by Gender")
plt.xlabel("Gender")
plt.ylabel("Mean recorded visits")
plt.show()

illness_analysis = (
    df.groupby("illness")["visits"]
        .agg(["count", "mean"])
        .reset_index()
)

display(illness_analysis)

sns.lineplot(
    data=illness_analysis,
    x="illness",
    y="mean",
    marker="o"
)

plt.title("Illness Score vs. Average Doctor Visits")
plt.xlabel("Illness score")
plt.ylabel("Mean recorded visits")
plt.show()

"""### Additional Univariate Analysis

Let's continue with more univariate plots to understand the distribution of `health`, `reduced`, and `private`.
"""

# Plotting histograms for 'health' and 'reduced'
