# Plotting a count plot for 'private' insurance
plt.figure(figsize=(7, 6))
sns.countplot(x='private', data=df, palette='Dark2', hue='private', legend=False)
plt.title('Distribution of Private Health Insurance')
plt.xlabel('Private Insurance (yes/no)')
plt.ylabel('Count')
plt.show()

"""### Multivariate Analysis

Let's explore the relationships between different variables using multivariate plots.
"""

# Scatter plot of Age vs. Visits
plt.figure(figsize=(10, 6))
sns.scatterplot(x='age', y='visits', data=df, alpha=0.6, color='darkblue')
plt.title('Age vs. Number of Doctor Visits')
plt.xlabel('Age')
plt.ylabel('Number of Visits')
plt.grid(True, linestyle='--', alpha=0.7)
plt.show()

# Scatter plot of Income vs. Visits
plt.figure(figsize=(10, 6))
sns.scatterplot(x='income', y='visits', data=df, alpha=0.6, color='darkgreen')
plt.title('Income vs. Number of Doctor Visits')
plt.xlabel('Income')
plt.ylabel('Number of Visits')
plt.grid(True, linestyle='--', alpha=0.7)
plt.show()

# Box plot of Income by Gender
plt.figure(figsize=(10, 6))
sns.boxplot(x='gender', y='income', data=df, palette='pastel', hue='gender', legend=False)
plt.title('Income Distribution by Gender')
plt.xlabel('Gender')
plt.ylabel('Income')
plt.grid(axis='y', linestyle='--', alpha=0.7)
plt.show()

# Box plot of Visits by Health Status
plt.figure(figsize=(12, 6))
